        private void AddAuditInfo()
        {
            var currentUserId = _userIdAccessor.GetCurrentUserId();

            var modifiedEntries = ChangeTracker.Entries()
                .Where(x => x.Entity is IAuditableEntity &&
                           (x.State == EntityState.Added || x.State == EntityState.Modified));

            foreach (var entry in modifiedEntries)
            {
                var entity = (IAuditableEntity)entry.Entity;
                var now = DateTime.UtcNow;

                if (entry.State == EntityState.Added)
                {
                    entity.CreatedDate = now;
                    entity.CreatedBy = currentUserId;
                }
                else
                {
                    base.Entry(entity).Property(x => x.CreatedBy).IsModified = false;
                    base.Entry(entity).Property(x => x.CreatedDate).IsModified = false;
                }

                entity.UpdatedDate = now;
                entity.UpdatedBy = currentUserId;
            }
        }

        private void AddAutomaticAuditLogs()
        {
            if (_isAddingAutomaticAuditLogs)
            {
                return;
            }

            if (!IsAuditLogTableAvailable())
            {
                return;
            }

            var currentUserId = _userIdAccessor.GetCurrentUserId();
            var entries = ChangeTracker.Entries()
                .Where(e => e.Entity is not AuditLog
                            && (e.State == EntityState.Added
                                || e.State == EntityState.Modified
                                || e.State == EntityState.Deleted)
                            && ShouldAuditEntry(e))
                .ToList();

            if (entries.Count == 0)
            {
                return;
            }

            _isAddingAutomaticAuditLogs = true;

            try
            {
                foreach (var entry in entries)
                {
                    var eventType = entry.State == EntityState.Added
                        ? "Create"
                        : entry.State == EntityState.Modified
                            ? "Update"
                            : "Delete";

                    var details = BuildAuditDetails(entry);
                    if (string.IsNullOrWhiteSpace(details))
                    {
                        continue;
                    }

                    var entityType = entry.Metadata.ClrType.Name;
                    AuditLogs.Add(new AuditLog
                    {
                        TranCode = ResolveTranCode(entry),
                        EventType = eventType,
                        Summary = $"{entityType} {eventType}",
                        Details = details,
                        Severity = "Info",
                        EntityType = entityType,
                        EntityId = ResolveEntityId(entry),
                        PerformedBy = currentUserId,
                        UserId = currentUserId,
                        EventDateTime = DateTime.UtcNow,
                        Status = "Logged"
                    });
                }
            }
            finally
            {
                _isAddingAutomaticAuditLogs = false;
            }
        }

        private bool IsAuditLogTableAvailable()
        {
            if (_isAuditLogTableAvailable.HasValue)
            {
                return _isAuditLogTableAvailable.Value;
            }

            try
            {
                var connection = Database.GetDbConnection();
                var shouldClose = connection.State != ConnectionState.Open;

                if (shouldClose)
                {
                    connection.Open();
                }

                try
                {
                    using var command = connection.CreateCommand();
                    command.CommandText = "SELECT 1 FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'AppAuditLogs'";
                    var result = command.ExecuteScalar();
                    _isAuditLogTableAvailable = result != null && result != DBNull.Value;
                }
                finally
                {
                    if (shouldClose)
                    {
                        connection.Close();
                    }
                }
            }
            catch
            {
                _isAuditLogTableAvailable = false;
            }

            return _isAuditLogTableAvailable.Value;
        }

        private static bool ShouldAuditEntry(EntityEntry entry)
        {
            var clrType = entry.Metadata.ClrType;
            var entityNamespace = clrType.Namespace ?? string.Empty;

            if (entityNamespace.StartsWith("AestheticEMR.Core.Models.Legacy", StringComparison.Ordinal))
            {
                return false;
            }

            var tableName = entry.Metadata.GetTableName();
            if (!string.IsNullOrWhiteSpace(tableName)
                && (tableName.StartsWith("AspNet", StringComparison.OrdinalIgnoreCase)
                    || tableName.StartsWith("vw", StringComparison.OrdinalIgnoreCase)
                    || tableName.StartsWith("qry", StringComparison.OrdinalIgnoreCase)))
            {
                return false;
            }

            return true;
        }

        private static string ResolveTranCode(EntityEntry entry)
        {
            var candidatePropertyNames = new[]
            {
                "ConsultId", "consultID", "BillNo", "billNO", "PNo", "Pno", "LabNo", "TranCode"
            };

            foreach (var propertyName in candidatePropertyNames)
            {
                var property = entry.Properties.FirstOrDefault(p =>
                    string.Equals(p.Metadata.Name, propertyName, StringComparison.OrdinalIgnoreCase));

                if (property is null)
                {
                    continue;
                }

                var rawValue = entry.State == EntityState.Deleted ? property.OriginalValue : property.CurrentValue;
                var value = rawValue?.ToString()?.Trim();

                if (!string.IsNullOrWhiteSpace(value))
                {
                    return value;
                }
            }

            return "GENERAL";
        }

        private static int? ResolveEntityId(EntityEntry entry)
        {
            var primaryKey = entry.Metadata.FindPrimaryKey();
            var keyProperty = primaryKey?.Properties.FirstOrDefault();
            if (keyProperty is null)
            {
                return null;
            }

            var keyEntry = entry.Property(keyProperty.Name);
            var rawValue = entry.State == EntityState.Deleted ? keyEntry.OriginalValue : keyEntry.CurrentValue;

            if (rawValue is int intValue)
            {
                return intValue;
            }

            if (rawValue is long longValue && longValue <= int.MaxValue && longValue >= int.MinValue)
            {
                return (int)longValue;
            }

            if (rawValue is string strValue && int.TryParse(strValue, out var parsedValue))
            {
                return parsedValue;
            }

            return null;
        }

        private static string BuildAuditDetails(EntityEntry entry)
        {
            var properties = entry.Properties.Where(p =>
                !p.Metadata.IsPrimaryKey()
                && p.Metadata.Name != nameof(IAuditableEntity.CreatedBy)
                && p.Metadata.Name != nameof(IAuditableEntity.CreatedDate)
                && p.Metadata.Name != nameof(IAuditableEntity.UpdatedBy)
                && p.Metadata.Name != nameof(IAuditableEntity.UpdatedDate)
                && p.Metadata.ClrType != typeof(byte[]));

            var details = entry.State == EntityState.Added
                ? properties
                    .Where(p => p.CurrentValue != null)
                    .Select(p => $"{p.Metadata.Name}: {p.CurrentValue}")
                : entry.State == EntityState.Deleted
                    ? properties
                        .Where(p => p.OriginalValue != null)
                        .Select(p => $"{p.Metadata.Name}: {p.OriginalValue}")
                    : properties
                        .Where(p => p.IsModified && !Equals(p.OriginalValue, p.CurrentValue))
                        .Select(p => $"{p.Metadata.Name}: '{p.OriginalValue}' -> '{p.CurrentValue}'");

            return string.Join("; ", details);
